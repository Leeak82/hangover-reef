// Server-authority checks over the real WebSocket protocol. Usage: node scripts/security-test.mjs [baseUrl]
import WebSocket from 'ws';
const BASE = process.argv[2] || 'http://localhost:8787';
const r = await fetch(BASE + '/api/auth/signup', { method: 'POST', headers: { 'content-type': 'application/json' }, body: JSON.stringify({ email: `sec${Date.now()}@example.com`, password: 'partyhard123', ageConfirmed: true }) });
const cookie = r.headers.get('set-cookie').split(';')[0];
const me = async () => (await (await fetch(BASE + '/api/auth/me', { headers: { cookie } })).json()).user.coins;
const ok = (c, m) => console.log(c ? 'PASS' : 'FAIL', m);
ok((await fetch(BASE + '/api/auth/signup', { method: 'POST', headers: { 'content-type': 'application/json' }, body: JSON.stringify({ email: `x${Date.now()}@example.com`, password: 'partyhard123', ageConfirmed: false }) })).status === 400, 'signup without age confirmation rejected');
ok(r.headers.get('set-cookie').toLowerCase().includes('httponly'), 'session cookie is httpOnly');
const ws = new WebSocket(BASE.replace('http', 'ws') + '/ws', { headers: { cookie, origin: BASE } });
const msgs = []; let waiters = [];
ws.on('message', d => { const m = JSON.parse(d); if (m.t === 'spawn') return; msgs.push(m); waiters.forEach(w => w()); });
const next = (pred, ms = 1500) => new Promise(res => { const f = () => { const i = msgs.findIndex(pred); if (i >= 0) { res(msgs.splice(i, 1)[0]); return true; } }; if (f()) return; const w = () => { if (f()) { clearTimeout(t); waiters = waiters.filter(x => x !== w); } }; const t = setTimeout(() => { waiters = waiters.filter(x => x !== w); res(null); }, ms); waiters.push(w); });
await new Promise(res => ws.on('open', res));
ws.send(JSON.stringify({ t: 'join', room: 'vip' }));
ok((await next(m => m.t === 'error'))?.reason.includes('10,000'), 'VIP room refused with 2,000 coins');
ws.send(JSON.stringify({ t: 'join', room: 'happy' }));
const joined = await next(m => m.t === 'joined'); ok(joined && joined.fish.length > 20, `joined happy with ${joined?.fish.length} fish`);
ws.send(JSON.stringify({ t: 'fire', bet: 1000, cid: 1 }));
ok((await next(m => m.cid === 1))?.t === 'reject', 'bet outside room range rejected');
ws.send(JSON.stringify({ t: 'fire', bet: 10, cid: 2 }));
const fired = await next(m => m.cid === 2); ok(fired?.t === 'fired' && fired.balance === 1990, 'valid shot debits server balance');
ws.send(JSON.stringify({ t: 'hit', bid: fired.bid, fid: 99999 }));
ok((await next(m => m.t === 'hit', 600)) === null, 'hit on non-existent fish ignored');
const target = joined.fish.find(f => f.kind === 'sardine') || joined.fish[0];
ws.send(JSON.stringify({ t: 'hit', bid: fired.bid, fid: target.id }));
const h1 = await next(m => m.t === 'hit'); ok(!!h1, `hit resolved by server: killed=${h1?.killed} payout=${h1?.payout}`);
ws.send(JSON.stringify({ t: 'hit', bid: fired.bid, fid: target.id }));
ok((await next(m => m.t === 'hit', 600)) === null, 'bullet cannot be reused');
ws.send(JSON.stringify({ t: 'hit', bid: 4242, fid: target.id }));
ok((await next(m => m.t === 'hit', 600)) === null, 'forged bullet id ignored');
// unused bullets are refunded on disconnect
ws.send(JSON.stringify({ t: 'fire', bet: 10, cid: 3 })); const f3 = await next(m => m.cid === 3);
const before = f3.balance; ws.close(); await new Promise(r => setTimeout(r, 400));
ok(await me() === before + 10, 'unused bullet refunded on leave');
const bad = new WebSocket(BASE.replace('http', 'ws') + '/ws');
ok(await new Promise(res => { bad.on('error', () => res(true)); bad.on('open', () => res(false)); }), 'unauthenticated socket refused');
const evil = new WebSocket(BASE.replace('http', 'ws') + '/ws', { headers: { cookie, origin: 'https://evil.example' } });
ok(await new Promise(res => { evil.on('error', () => res(true)); evil.on('open', () => res(false)); }), 'cross-origin socket refused');
ok((await fetch(BASE + '/api/shop/test-purchase', { method: 'POST', headers: { 'content-type': 'application/json' }, body: '{"packId":"p1"}' })).status === 401, 'test purchase requires login');
process.exit(0);
